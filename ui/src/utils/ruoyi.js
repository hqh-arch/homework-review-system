export function closeWindow() { // 关闭当前窗口
                                // 尝试关闭当前窗口/标签页
  if (window.opener) {
    // 如果是由其他窗口打开的，可以安全关闭
    window.close();
  } else {
    // 如果是直接访问的页面，尝试使用 HTML5 的 postMessage
    window.open('', '_self', '');
    window.close();
  }
  // 如果上述方法都不起作用（现代浏览器通常会阻止），给用户提示
  setTimeout(() => {
    this.$modal.msgWarning("浏览器安全限制，请手动关闭此标签页");
  }, 100);
}

